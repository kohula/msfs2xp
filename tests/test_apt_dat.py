        "18 47.505 8.505 3 400 1",
        "19 47.504 8.504 1",
        "20 47.501 8.500 0 0 5 0 A1",
        "21 47.507 8.507 0 3 2 VASI",
        "1500 47.5005 8.5005 0 90.0 12.0 1 GATE_A1",
        "120 taxi centerline",
